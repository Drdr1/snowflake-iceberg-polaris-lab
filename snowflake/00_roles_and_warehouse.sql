-- 00 - Roles, warehouse, database for the lab.
-- Run as ACCOUNTADMIN in a Snowflake trial. Separation of duties:
--   ICEBERG_ADMIN  owns integrations and external volumes (account-level objects)
--   LAB_ENGINEER   creates and maintains Iceberg tables
--   LAB_ANALYST    reads only
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ICEBERG_ADMIN;
CREATE ROLE IF NOT EXISTS LAB_ENGINEER;
CREATE ROLE IF NOT EXISTS LAB_ANALYST;
GRANT ROLE LAB_ANALYST   TO ROLE LAB_ENGINEER;
GRANT ROLE LAB_ENGINEER  TO ROLE ICEBERG_ADMIN;
GRANT ROLE ICEBERG_ADMIN TO ROLE SYSADMIN;
SET me = CURRENT_USER();
GRANT ROLE ICEBERG_ADMIN TO USER IDENTIFIER($me);

GRANT CREATE EXTERNAL VOLUME ON ACCOUNT TO ROLE ICEBERG_ADMIN;
GRANT CREATE INTEGRATION     ON ACCOUNT TO ROLE ICEBERG_ADMIN;
GRANT CREATE DATABASE        ON ACCOUNT TO ROLE ICEBERG_ADMIN;

-- XSMALL with a 60s auto-suspend: keeps the trial credits for the tests.
CREATE WAREHOUSE IF NOT EXISTS LAB_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE LAB_WH TO ROLE LAB_ANALYST;

USE ROLE ICEBERG_ADMIN;
CREATE DATABASE IF NOT EXISTS LAKEHOUSE_LAB;
CREATE SCHEMA IF NOT EXISTS LAKEHOUSE_LAB.EXTERNAL_CATALOG;  -- tables owned by Polaris
CREATE SCHEMA IF NOT EXISTS LAKEHOUSE_LAB.SNOWFLAKE_MANAGED; -- tables owned by Snowflake

GRANT USAGE ON DATABASE LAKEHOUSE_LAB TO ROLE LAB_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE LAKEHOUSE_LAB TO ROLE LAB_ANALYST;
GRANT CREATE ICEBERG TABLE ON SCHEMA LAKEHOUSE_LAB.EXTERNAL_CATALOG  TO ROLE LAB_ENGINEER;
GRANT CREATE ICEBERG TABLE ON SCHEMA LAKEHOUSE_LAB.SNOWFLAKE_MANAGED TO ROLE LAB_ENGINEER;
GRANT SELECT ON FUTURE ICEBERG TABLES IN DATABASE LAKEHOUSE_LAB TO ROLE LAB_ANALYST;
